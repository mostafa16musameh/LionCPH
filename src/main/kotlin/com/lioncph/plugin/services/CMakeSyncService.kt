package com.lioncph.plugin.services

import com.intellij.openapi.actionSystem.ActionManager
import com.intellij.openapi.application.ApplicationManager
import com.intellij.openapi.project.Project
import com.intellij.openapi.vfs.LocalFileSystem
import com.intellij.openapi.wm.WindowManager
import com.lioncph.plugin.models.CphStorage
import java.nio.charset.StandardCharsets
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.attribute.FileTime

/**
 * Manages LionCPH's isolated CMake targets inside `.cph/lioncph_targets.cmake`
 * without altering any user-owned targets or files in CMakeLists.txt.
 */
object CMakeSyncService {
    private const val INCLUDE_LINE = "include(\"\${CMAKE_CURRENT_SOURCE_DIR}/.cph/lioncph_targets.cmake\" OPTIONAL)"
    private const val INCLUDE_COMMENT = "# LionCPH auto-managed targets (safe & optional)"

    fun registerPluginFile(projectRoot: Path, rawTarget: String, relativeFilePath: String) {
        val settings = CphStorage.loadSettings(projectRoot)
        if (!settings.autoSyncCMake) return

        val cmakeFile = projectRoot.resolve("CMakeLists.txt")
        if (!Files.isRegularFile(cmakeFile)) return

        runCatching {
            val mainContent = Files.readString(cmakeFile, StandardCharsets.UTF_8)

            // If the user already uses file(GLOB ...) for *.cpp in the root, do not duplicate targets;
            // just touch CMakeLists.txt so CLion reloads the new file.
            val normRel = relativeFilePath.replace('\\', '/')
            val isInSubdir = normRel.contains('/')
            val hasRootGlob = Regex("""file\s*\(\s*GLOB\s+\w+(?:\s+CONFIGURE_DEPENDS)?\s+"?(?:\$\{CMAKE_(?:CURRENT_)?SOURCE_DIR\}/)?\*\.cpp"?""", RegexOption.IGNORE_CASE).containsMatchIn(mainContent)
            val hasRecurseGlob = Regex("""file\s*\(\s*GLOB_RECURSE\s+\w+(?:\s+CONFIGURE_DEPENDS)?\s+"?(?:\$\{CMAKE_(?:CURRENT_)?SOURCE_DIR\}/)?\*\.cpp"?""", RegexOption.IGNORE_CASE).containsMatchIn(mainContent)
            if (hasRecurseGlob || (!isInSubdir && hasRootGlob)) {
                Files.setLastModifiedTime(cmakeFile, FileTime.fromMillis(System.currentTimeMillis()))
                return
            }

            // Ensure the single safe OPTIONAL include line exists in CMakeLists.txt (added once)
            if (!mainContent.contains(".cph/lioncph_targets.cmake")) {
                val sep = if (mainContent.endsWith("\n") || mainContent.isEmpty()) "\n" else "\n\n"
                val updatedMain = "$mainContent$sep$INCLUDE_COMMENT\n$INCLUDE_LINE\n"
                Files.writeString(cmakeFile, updatedMain, StandardCharsets.UTF_8)
            }

            // Manage LionCPH targets exclusively in .cph/lioncph_targets.cmake
            val cphDir = projectRoot.resolve(".cph")
            Files.createDirectories(cphDir)
            val targetsFile = cphDir.resolve("lioncph_targets.cmake")
            val existing = if (Files.isRegularFile(targetsFile)) {
                Files.readString(targetsFile, StandardCharsets.UTF_8)
            } else {
                "# Auto-generated by LionCPH — contains only files created by LionCPH\n"
            }

            // Skip if already registered in either CMakeLists.txt or lioncph_targets.cmake
            if (mainContent.contains(normRel) || existing.contains(normRel)) {
                syncOnlineJudgeMacro(projectRoot, settings.setOnlineJudge, null)
                return
            }

            var target = rawTarget.replace(Regex("[^a-zA-Z0-9_\\-]"), "_")
            if (target.isEmpty() || target[0].isDigit()) {
                target = "prob_$target"
            }
            var uniqueTarget = target
            var suffix = 2
            val combined = mainContent + "\n" + existing
            while (Regex("""add_executable\s*\(\s*${Regex.escape(uniqueTarget)}\b""").containsMatchIn(combined)) {
                uniqueTarget = "${target}_$suffix"
                suffix++
            }

            val macroDef = if (settings.setOnlineJudge) "ONLINE_JUDGE" else "LOCAL"
            val sep = if (existing.endsWith("\n") || existing.isEmpty()) "" else "\n"
            val block = buildString {
                append(sep)
                append("if(EXISTS \"\${CMAKE_CURRENT_SOURCE_DIR}/$normRel\" AND NOT TARGET $uniqueTarget)\n")
                append("    add_executable($uniqueTarget \"\${CMAKE_CURRENT_SOURCE_DIR}/$normRel\")\n")
                append("    target_compile_definitions($uniqueTarget PRIVATE $macroDef)\n")
                append("endif()\n")
            }
            Files.writeString(targetsFile, existing + block, StandardCharsets.UTF_8)
        }
    }

    /**
     * Updates ONLINE_JUDGE / LOCAL macro definitions for LionCPH-managed targets
     * so CLion's editor highlighting matches the Set ONLINE_JUDGE toggle.
     */
    fun syncOnlineJudgeMacro(projectRoot: Path, setOnlineJudge: Boolean, project: Project?) {
        val targetsFile = projectRoot.resolve(".cph").resolve("lioncph_targets.cmake")
        if (!Files.isRegularFile(targetsFile)) return

        runCatching {
            val content = Files.readString(targetsFile, StandardCharsets.UTF_8)
            val updated = if (setOnlineJudge) {
                content.replace("PRIVATE LOCAL)", "PRIVATE ONLINE_JUDGE)")
            } else {
                content.replace("PRIVATE ONLINE_JUDGE)", "PRIVATE LOCAL)")
            }
            if (updated != content) {
                Files.writeString(targetsFile, updated, StandardCharsets.UTF_8)
                triggerCMakeReload(projectRoot, project)
            }
        }
    }

    /**
     * Programmatically refreshes VFS and reloads CMake with explicit project frame context
     * so reload succeeds even if CLion's auto-reload is disabled or focus is outside the editor.
     */
    fun triggerCMakeReload(projectRoot: Path, project: Project? = null) {
        ApplicationManager.getApplication().invokeLater {
            LocalFileSystem.getInstance().refreshAndFindFileByNioFile(projectRoot.resolve("CMakeLists.txt"))?.refresh(true, false)
            LocalFileSystem.getInstance().refreshAndFindFileByNioFile(projectRoot.resolve(".cph/lioncph_targets.cmake"))?.refresh(true, false)
            runCatching {
                val am = ActionManager.getInstance()
                val reloadAction = am.getAction("CMake.ReloadCMakeProject")
                if (reloadAction != null) {
                    val frameComp = project?.let { WindowManager.getInstance().getFrame(it) }
                    am.tryToExecute(reloadAction, null, frameComp, null, true)
                }
            }
        }
    }
}
